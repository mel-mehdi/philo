#include "../../philo.h"

long	ft_atoi(char *n)
{
	long	i;
	long	j;
	long	nb;

	i = 0;
	j = 1;
	while ((n[i] >= 9 && n[i] <= 13) || n[i] == 32)
		i++;
	if (n[i] == '-' || n[i] == '+')
	{
		if (n[i++] == '-')
			j = -1;
	}
	nb = 0;
	while (n[i] != '\0')
	{
		if (ft_isdigit(n[i]) == 0)
			return (nb * j);
		nb = (nb * 10) + (n[i++] - 48);
		if ((j == 1 && nb > 2147483647))
			return (-1);
		else if (j == -1 && nb > 2147483648)
			return (-1);
	}
	return (nb * j);
}
